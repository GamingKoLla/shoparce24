/**
 * Calculates Buy & Sell price according to ArcEdge Central Pricing Architecture:
 * 1. Explicit manual prices in config override everything.
 * 2. If item is missing manual price:
 *    Buy = item.manualBuy ?? config.defaultBuyPrice
 *    Sell = Math.floor(Buy * config.sellPriceRatio) [or manualSell if defined]
 * 3. Loop Guard: Sell price is guaranteed to be strictly lower than Buy price.
 */
export function resolveItemPrices(
  item: MCItem,
  config: ShopPricingConfig
): { buy: number; sell: number; isManual: boolean; loopSafe: boolean } {
  const manual = config.manualPrices[item.materialName];
  if (manual) {
    const loopSafe = manual.buy > manual.sell;
    return {
      buy: Math.max(1, manual.buy),
      sell: Math.max(0, manual.sell),
      isManual: true,
      loopSafe,
    };
  }

  // Auto-pricing algorithm with configurable defaults
  const baseBuy = item.manualBuy ?? config.defaultBuyPrice;
  const calculatedSell = item.manualSell ?? Math.floor(baseBuy * config.sellPriceRatio);
  // Guarantee profit-loop safety: sell cannot exceed buy * 0.95
  const safeSell = Math.min(calculatedSell, Math.floor(baseBuy * 0.90));

  return {
    buy: Math.max(1, baseBuy),
    sell: Math.max(1, safeSell),
    isManual: false,
    loopSafe: baseBuy > safeSell,
  };
}
